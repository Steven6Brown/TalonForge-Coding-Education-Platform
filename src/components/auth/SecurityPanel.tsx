"use client";
import { useCallback, useEffect, useState } from "react";
import { auth, type AuthUser, type MfaEnrollment, type MfaFactor } from "@/lib/auth";
import { passwordIssues, totpCodeSchema } from "@/lib/auth/password-policy";
import { generateRecoveryCodes, recordAuthEvent } from "@/lib/auth/server/actions";
import { Alert, Field, PasswordField } from "./fields";

/** Account security center: password change, authenticator (TOTP) management, recovery codes, global sign-out. */
export function SecurityPanel({ user }: { user: AuthUser }) {
  return (
    <div className="stack">
      <section className="card">
        <h2>Account</h2>
        <p>{user.email} {user.emailVerified ? <span className="badge ok">Verified</span> : <span className="badge">Unverified</span>}</p>
        <p className="muted small">Role: {user.role}</p>
      </section>
      <PasswordChange email={user.email} />
      <MfaSection />
      <SessionsSection />
    </div>
  );
}

function PasswordChange({ email }: { email: string }) {
  const [pw, setPw] = useState("");
  const [msg, setMsg] = useState<{ kind: "ok" | "error"; text: string } | null>(null);
  async function submit(e: React.FormEvent) {
    e.preventDefault();
    const issues = passwordIssues(pw, email);
    if (issues.length) return setMsg({ kind: "error", text: issues[0] });
    const r = await auth.updatePassword(pw);
    if (r.ok) {
      setPw("");
      await recordAuthEvent("password_changed");
      setMsg({ kind: "ok", text: "Password updated." });
    } else setMsg({ kind: "error", text: r.error.message });
  }
  return (
    <form className="card" onSubmit={submit}>
      <h2>Change password</h2>
      {msg && <Alert kind={msg.kind}>{msg.text}</Alert>}
      <PasswordField label="New password" value={pw} onChange={setPw} email={email} mode="new" />
      <button className="btn primary">Update password</button>
    </form>
  );
}

function MfaSection() {
  const [factors, setFactors] = useState<MfaFactor[]>([]);
  const [enroll, setEnroll] = useState<MfaEnrollment | null>(null);
  const [code, setCode] = useState("");
  const [codes, setCodes] = useState<string[] | null>(null);
  const [msg, setMsg] = useState<{ kind: "ok" | "error"; text: string } | null>(null);

  const refresh = useCallback(async () => {
    const r = await auth.mfa.list();
    if (r.ok) setFactors(r.data.filter((f) => f.verified));
  }, []);
  useEffect(() => {
    void refresh();
  }, [refresh]);

  async function start() {
    setMsg(null);
    const r = await auth.mfa.enroll(`Authenticator ${new Date().toISOString().slice(0, 10)}`);
    if (r.ok) setEnroll(r.data);
    else setMsg({ kind: "error", text: r.error.message });
  }
  async function confirm(e: React.FormEvent) {
    e.preventDefault();
    if (!enroll) return;
    const parsed = totpCodeSchema.safeParse(code);
    if (!parsed.success) return setMsg({ kind: "error", text: parsed.error.issues[0].message });
    const r = await auth.mfa.confirmEnrollment(enroll.factorId, parsed.data);
    if (!r.ok) return setMsg({ kind: "error", text: r.error.message });
    setEnroll(null);
    setCode("");
    await recordAuthEvent("mfa_enrolled");
    const rc = await generateRecoveryCodes(); // shown once; only hashes are stored
    if (rc.ok) setCodes(rc.data);
    await refresh();
  }
  async function remove(id: string) {
    const r = await auth.mfa.unenroll(id);
    if (r.ok) {
      await recordAuthEvent("mfa_removed");
      await refresh();
    } else setMsg({ kind: "error", text: r.error.message });
  }

  return (
    <section className="card">
      <h2>Two-step verification (authenticator app)</h2>
      {msg && <Alert kind={msg.kind}>{msg.text}</Alert>}
      {factors.length === 0 && !enroll && (
        <>
          <p className="muted">Add an extra layer of protection with an app like Google Authenticator, 1Password or Authy.</p>
          <button className="btn primary" onClick={start}>Set up authenticator</button>
        </>
      )}
      {enroll && (
        <form onSubmit={confirm}>
          <p>Scan this QR code with your authenticator app, then enter the 6-digit code.</p>
          {/* QR is a data: URI generated by the auth server */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={enroll.qrDataUri} alt="QR code for your authenticator app" width={180} height={180} className="qr" />
          <p className="muted small">Can&apos;t scan? Enter this key manually: <code>{enroll.secret}</code></p>
          <Field label="6-digit code" value={code} onChange={setCode} inputMode="numeric" autoComplete="one-time-code" maxLength={6} />
          <button className="btn primary">Verify and enable</button>
        </form>
      )}
      {factors.map((f) => (
        <p key={f.id} className="row">
          <span>🔐 {f.friendlyName}</span>
          <button className="btn small danger" onClick={() => remove(f.id)}>Remove</button>
        </p>
      ))}
      {factors.length > 0 && (
        <button className="btn" onClick={async () => { const r = await generateRecoveryCodes(); if (r.ok) setCodes(r.data); else setMsg({ kind: "error", text: r.message }); }}>
          Generate new recovery codes
        </button>
      )}
      {codes && (
        <div className="codes" role="region" aria-label="Recovery codes">
          <p><strong>Save these recovery codes now.</strong> Each works once and they won&apos;t be shown again.</p>
          <ul>{codes.map((c) => <li key={c}><code>{c}</code></li>)}</ul>
          <button className="btn small" onClick={() => setCodes(null)}>I&apos;ve saved them</button>
        </div>
      )}
    </section>
  );
}

function SessionsSection() {
  const [done, setDone] = useState(false);
  return (
    <section className="card">
      <h2>Sessions</h2>
      <p className="muted">Sign out of every device, including this one. Do this if you suspect someone else has access.</p>
      {done && <Alert kind="ok">Signed out everywhere.</Alert>}
      <button
        className="btn danger"
        onClick={async () => {
          await recordAuthEvent("sign_out_everywhere");
          await auth.signOut("global");
          setDone(true);
          window.location.assign("/login");
        }}
      >
        Sign out everywhere
      </button>
    </section>
  );
}
